#!/usr/bin/env node
// port/foh/face-lint.js — THE FACE-DOMAIN LINT (spec #20, ticket #24).
//
// WHAT THIS IS, AND WHY IT IS THE THIRD LAYER
// -------------------------------------------
// A string is only DRAWABLE if every character in it is in the face (see
// CONTEXT.md, "Face domain"). There are three defences against a string that
// is not, and they are deliberately different in kind:
//
//   1. #21's rendering check — the witness RENDERS every frame it simulates,
//      so any string a test actually reaches is drawn and judged.
//   2. #21's runtime split — a miss is a gfx_fatal in a check build and a
//      visible placeholder box in the product build.
//   3. THIS LINT — the NAME TABLES. Tool names, wall types, damage types,
//      pause rows, character names, the credits: data that reaches the
//      renderer with no call site of its own. Layer 1 only sees such an
//      entry if a test happens to draw that exact row, and a test would have
//      to visit all ten tool names and all four damage types to see them all.
//      This layer reads the tables instead of waiting to be shown one.
//
// THE DOMAIN IS READ, NEVER RESTATED. This script does not contain a list of
// drawable characters. It refuses to run without a probe dump produced by
// port/foh/face_lint_probe.c, which asks foh_font.c itself through
// `foh_face_domain`. Restating a constant instead of reading it is how four
// separate device checks went stale in one week in this project.
//
// TWO FACES, AND THE HOLE THAT MUST STAY. foh_font.c carries kGlyphs (5x7)
// and kGlyphs2 (6x9). Their domains differ by exactly ONE glyph — face 1 has
// no '?' — and that hole is load-bearing: check-foh-flows.sh's finish-banner
// tooth proves the loud missing-glyph failure by drawing "COMPLETE?" through
// face 1. So every drawn table here declares WHICH FACE its draw site uses,
// and a face-1 failure is never to be fixed by adding the character to face
// 1. See this file's fail() text and foh_font.c's note.
//
// ===========================================================================
// WHAT THIS LINT DOES NOT COVER  (read this before trusting it)
// ===========================================================================
// It is a SOURCE SCAN plus a small runtime probe. It is a net UNDER layers 1
// and 2, never a replacement for them, because:
//
//   (a) IT CANNOT SEE THROUGH STRING ASSEMBLY. Several drawn strings are
//       built at draw time from a table lookup plus a number — the target
//       builder's HUD is literally
//         snprintf(line, ..., "%s%s%s   GRID %d", tool, ...)
//       (foh_render.c). This lint checks `tool` (kToolNames) and the format's
//       own literal characters are checked only where they are passed
//       directly to foh_text/foh_text2; it cannot check what %d or %s
//       produce. Layer 1 draws the assembled string; layer 2 survives it.
//   (b) IT ONLY SEES TABLES. A one-off literal handed to a helper wrapper
//       (text_in, text_center, text2_center, header, tb_msg) is not a table
//       and is not scanned; only literals passed DIRECTLY to foh_text or
//       foh_text2 are. Refusal strings set through a message setter are in
//       that gap, and layer 1 is what covers them.
//   (c) IT CANNOT EXPAND MACROS. A table generated by an X-macro (e.g.
//       foh_pause.c's drain_held_names) contains no literal for the scanner
//       to find. That one is a stderr diagnostic, not a drawn string, but a
//       DRAWN X-macro table would be invisible here.
//   (d) IT IS STATIC. A string that arrives from outside the tree — a file,
//       an argv, a share code — has no literal anywhere. Those are validated
//       where they are read (foh_tbuild.c's grammar), not here.
//
// ===========================================================================
// Usage:
//   node port/foh/face-lint.js --probe <probe-dump> [--overlay <dir>]
//
// --overlay lets a tooth point the scan at a PERTURBED COPY of one file
// without writing the committed tree: every census path is read from
// <dir>/<path> when that exists and from the repo otherwise.
//
// Exit 0 and `FACE LINT PASS` on success; nonzero with a named entry on any
// failure. `bash port/foh/check-face-lint.sh` is the runnable check.

'use strict';

const fs = require('fs');
const path = require('path');
const cp = require('child_process');

// --- args -------------------------------------------------------------------
let probePath = null;
let overlay = null;
for (let i = 2; i < process.argv.length; i++) {
  const a = process.argv[i];
  if (a === '--probe') probePath = process.argv[++i];
  else if (a === '--overlay') overlay = process.argv[++i];
  else die(`unknown argument |${a}|`);
}
if (!probePath) die('--probe <file> is required: the domain is READ from the ' +
  'font (port/foh/face_lint_probe.c), never restated here');

let failures = 0;
function die(msg) {
  console.error('FACE LINT FAIL: ' + msg);
  process.exit(2);
}
function bad(msg) {
  console.error('FACE LINT FAIL: ' + msg);
  failures++;
}

// --- [1] the domain, read out of foh_font.c ---------------------------------
// The probe dump's grammar is strict and its END marker is required, so a
// truncated or half-written dump can never be mistaken for a small domain.
const probeRaw = fs.readFileSync(probePath, 'utf8');
const probeLines = probeRaw.split('\n');
if (!probeLines.includes('END')) {
  die(`the probe dump ${probePath} has no END marker — it is truncated, and a ` +
    'truncated domain would silently pass everything');
}
const domain = { face1: null, face2: null };
const runtimeRows = [];
for (const ln of probeLines) {
  if (ln === '' || ln === 'END') continue;
  let m = /^DOMAIN ([12]) (\d+)((?: [0-9a-f]{2})+)$/.exec(ln);
  if (m) {
    const chars = m[3].trim().split(' ').map((h) => String.fromCharCode(parseInt(h, 16)));
    if (chars.length !== Number(m[2])) {
      die(`DOMAIN ${m[1]}: the probe declared ${m[2]} glyphs and listed ${chars.length}`);
    }
    domain['face' + m[1]] = new Set(chars);
    continue;
  }
  m = /^RUNTIME (\S+) (\S+) (face1|face2) (raw|upper) (\d+) (.*)$/.exec(ln);
  if (m) {
    runtimeRows.push({
      file: m[1], sym: m[2], face: m[3], xform: m[4],
      idx: Number(m[5]), text: m[6], line: 0,
    });
    continue;
  }
  die(`the probe dump has a line the grammar does not allow: |${ln}|`);
}
if (!domain.face1 || !domain.face2) {
  die('the probe dump is missing a DOMAIN line — both faces must be read');
}
// Face 1 is the SAFE domain only while it is a subset of face 2. Measured,
// never assumed: if a glyph ever exists in face 1 alone, `both` must stop
// meaning "face 1" and this says so instead of quietly narrowing.
