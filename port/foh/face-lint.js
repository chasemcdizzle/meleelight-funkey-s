// --- [3] the census ---------------------------------------------------------
// Scope: every committed C source and header under the three trees that can
// reach the font (port/foh, port/gfx, port/sim/target — measured: the only
// callers of foh_text/foh_text2 live in port/foh and port/gfx/gfx_target.c).
const CENSUS_GLOBS = [
  'port/foh/*.c', 'port/foh/*.h',
  'port/gfx/*.c', 'port/gfx/*.h',
  'port/sim/target/*.c', 'port/sim/target/*.h',
];
const files = cp
  .execSync('git ls-files -- ' + CENSUS_GLOBS.map((g) => `'${g}'`).join(' '),
            { encoding: 'utf8' })
  .trim().split('\n').filter(Boolean);
if (files.length < 40) die(`the census listed only ${files.length} files — ` +
  'run this from the repository root');

function readSource(rel) {
  if (overlay) {
    const o = path.join(overlay, rel);
    if (fs.existsSync(o)) return { text: fs.readFileSync(o, 'utf8'), from: o };
  }
  return { text: fs.readFileSync(rel, 'utf8'), from: rel };
}

// Comments out, string literals kept byte-for-byte (a `"` inside a comment
// must not open a literal, and a `//` inside a literal must not open a
// comment — both happen in this tree).
function stripComments(src) {
  let out = '', i = 0;
  const n = src.length;
  while (i < n) {
    const c = src[i];
    if (c === '"' || c === "'") {
      let j = i + 1;
      while (j < n) {
        if (src[j] === '\\') { j += 2; continue; }
        if (src[j] === c) { j++; break; }
        j++;
      }
      out += src.slice(i, j); i = j; continue;
    }
    if (c === '/' && src[i + 1] === '/') {
      let j = src.indexOf('\n', i);
      if (j < 0) j = n;
      i = j; continue;
    }
    if (c === '/' && src[i + 1] === '*') {
      let j = src.indexOf('*/', i + 2);
      j = j < 0 ? n : j + 2;
      out += ' '; i = j; continue;
    }
    out += c; i++;
  }
  return out;
}

// Skip forward over a balanced region, treating string literals as opaque.
function matchBrace(s, from, open, close) {
  let d = 1, i = from;
  while (i < s.length && d > 0) {
    const c = s[i];
    if (c === '"') {
      let j = i + 1;
      while (j < s.length) {
        if (s[j] === '\\') { j += 2; continue; }
        if (s[j] === '"') { j++; break; }
        j++;
      }
      i = j; continue;
    }
    if (c === open) d++;
    else if (c === close) d--;
    i++;
  }
  return i - 1; // index of the closing delimiter
}

function unescapeC(lit) {
  return lit.replace(/\\(x[0-9a-fA-F]{1,2}|[0-7]{1,3}|.)/g, (m, e) => {
    if (e[0] === 'x') return String.fromCharCode(parseInt(e.slice(1), 16));
    if (/^[0-7]+$/.test(e)) return String.fromCharCode(parseInt(e, 8));
    const map = { n: '\n', t: '\t', r: '\r', '0': '\0', '\\': '\\', '"': '"', "'": "'" };
    return Object.prototype.hasOwnProperty.call(map, e) ? map[e] : e;
  });
}

function literalsIn(body) {
  return [...body.matchAll(/"((?:[^"\\]|\\.)*)"/g)].map((m) => unescapeC(m[1]));
}

const lineOf = (s, idx) => s.slice(0, idx).split('\n').length;

// Any array initializer that carries at least one string literal. This is
// wider than `const char *x[]` on purpose: the credits table is an array of
// STRUCTS whose members are drawn, and the first draft of this scan missed it.
const TABLE_RE = /\b(\w+)\s*((?:\[[^\]]*\]\s*)+)=\s*\{/g;
// Literals handed DIRECTLY to a font entry point. The face is the callee's,
// so these need no registry row (see NOT COVERED (b) for what this misses).
const CALL_RE = /\bfoh_text(2?)\s*\(/g;

const found = [];       // census rows
const directCalls = []; // literal-at-a-draw-site rows
for (const rel of files) {
  const { text } = readSource(rel);
  const s = stripComments(text);
  TABLE_RE.lastIndex = 0;
  const seenSym = new Map();
  let m;
  while ((m = TABLE_RE.exec(s))) {
    const close = matchBrace(s, TABLE_RE.lastIndex, '{', '}');
    const body = s.slice(TABLE_RE.lastIndex, close);
    const lits = literalsIn(body);
    if (lits.length === 0) continue;
    const sym = m[1];
    const nth = seenSym.get(sym) || 0;
    seenSym.set(sym, nth + 1);
    found.push({ file: rel, sym, nth, line: lineOf(s, m.index), lits });
  }
  CALL_RE.lastIndex = 0;
  while ((m = CALL_RE.exec(s))) {
    const close = matchBrace(s, CALL_RE.lastIndex, '(', ')');
    const args = s.slice(CALL_RE.lastIndex, close);
    for (const lit of literalsIn(args)) {
      directCalls.push({
        file: rel, sym: 'foh_text' + (m[1] || '') + '() literal',
        face: m[1] === '2' ? 'face2' : 'face1',
        line: lineOf(s, m.index), text: lit,
      });
    }
  }
}

// --- [4] census vs registry, both directions --------------------------------
const key = (r) => `${r.file}::${r.sym}#${r.nth || 0}`;
const regByKey = new Map();
for (const r of REGISTRY) {
  const k = key(r);
  if (regByKey.has(k)) die(`the registry has two rows for ${k}`);
  regByKey.set(k, r);
}
const seenKeys = new Set();
for (const t of found) {
  const k = key(t);
  seenKeys.add(k);
  if (!regByKey.has(k)) {
    bad(`${t.file}:${t.line} ${t.sym} is a table of ${t.lits.length} string(s) ` +
      `that this lint has never been told about.\n` +
      `  Add a row to REGISTRY in port/foh/face-lint.js saying whether it ` +
      `reaches the renderer:\n` +
      `    draw: 'face1' | 'face2'  — with the DRAW SITE cited in \`why\`\n` +
      `    draw: false              — with what the strings actually ARE\n` +
      `  A new name table must not arrive unchecked; that is the whole point ` +
      `of this leg.`);
  }
}
for (const r of REGISTRY) {
  if (!seenKeys.has(key(r))) {
    bad(`the registry claims ${key(r)} exists and the census cannot find it. ` +
      `Either the table was renamed or removed (update port/foh/face-lint.js ` +
      `in the same change) or the scanner stopped recognising its shape — and ` +
      `a registry that describes tables which are not there is exactly how a ` +
      `check goes quietly vacuous.`);
  }
}

// --- [5] the judgment -------------------------------------------------------
function faceLabel(face) {
  return face === 'both' ? 'face1 & face2 (intersection)' : face;
}
function checkString(where, face, raw, xform) {
  const text = xform === 'upper' ? raw.toUpperCase() : raw;
  const dom = domainFor(face);
  for (const ch of text) {
    if (dom.has(ch)) continue;
    const hex = ch.charCodeAt(0).toString(16).padStart(2, '0');
    const shown = ch === '\n' ? '\\n' : ch === '\t' ? '\\t' : ch;
    bad(`${where}\n` +
      `  string  : "${raw}"${xform === 'upper' ? ` (drawn as "${text}")` : ''}\n` +
      `  offender: '${shown}' (0x${hex}) is not in ${faceLabel(face)}\n` +
      `  This string cannot be drawn: it is a gfx_fatal in a check build and a ` +
      `placeholder box for the player.\n` +
      `  FIX THE STRING, or — if this entry is really drawn in the other face — ` +
      `fix the face this table declares in port/foh/face-lint.js and cite the ` +
      `draw site.\n` +
      `  DO NOT widen face 1 to make this pass: face 1's missing '?' is held ` +
      `hostage by check-foh-flows.sh's finish-banner tooth (foh_font.c's note).`);
    return;
  }
}

let checkedTables = 0, checkedStrings = 0;
for (const t of found) {
  const r = regByKey.get(key(t));
  if (!r || !r.draw) continue;
  checkedTables++;
  t.lits.forEach((lit, i) => {
    checkedStrings++;
    checkString(`${t.file}:${t.line} ${t.sym}[${i}]`, r.draw, lit, r.xform);
  });
}
for (const r of runtimeRows) {
  checkedStrings++;
  checkString(`${r.file} ${r.sym}[${r.idx}] (runtime, from the probe)`,
              r.face, r.text, r.xform);
}
for (const c of directCalls) {
  checkedStrings++;
  checkString(`${c.file}:${c.line} ${c.sym}`, c.face, c.text, 'raw');
}

